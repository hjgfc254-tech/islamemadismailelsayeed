import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile, stat } from 'node:fs/promises';
import path from 'node:path';

const root = process.cwd();
const mapPath = 'docs/AI_PROJECT_MAP.json';
const indexPath = 'docs/AI_CONTEXT/FILE_INDEX.json';
const ignoredDirs = new Set(['.git', 'node_modules']);
const selfHashPaths = new Set([mapPath, indexPath]);
const sha = (bytes) => createHash('sha256').update(bytes).digest('hex');
const areaOf = (file) => file.split('/')[0] === 'apps' ? file.split('/').slice(0, 2).join('/') : (file.split('/')[0] || 'root');
const actual = new Set();

async function walk(dir = root) {
  for (const item of await readdir(dir, { withFileTypes: true })) {
    if (ignoredDirs.has(item.name)) continue;
    const absolute = path.join(dir, item.name);
    const relative = path.relative(root, absolute).replaceAll('\\', '/');
    if (item.isDirectory()) await walk(absolute);
    else actual.add(relative);
  }
}

function csvCell(value) {
  const text = String(value ?? '');
  return /[",\n\r]/.test(text) ? `"${text.replaceAll('"', '""')}"` : text;
}

function makeTree() {
  const lines = ['# Current Project Tree', '', '> Generated from the current working tree. Human reference only; use `docs/AI_CONTEXT/FILE_INDEX.json` for fast AI lookup.', '', '```text', 'hansalhlak/'];
  async function append(dir, prefix = '') {
    const items = (await readdir(dir, { withFileTypes: true }))
      .filter((item) => !ignoredDirs.has(item.name))
      .sort((a, b) => Number(b.isDirectory()) - Number(a.isDirectory()) || a.name.localeCompare(b.name));
    for (let i = 0; i < items.length; i++) {
      const item = items[i], last = i === items.length - 1;
      lines.push(prefix + (last ? '└── ' : '├── ') + item.name + (item.isDirectory() ? '/' : ''));
      if (item.isDirectory()) await append(path.join(dir, item.name), prefix + (last ? '    ' : '│   '));
    }
  }
  return append(root).then(() => lines.concat('```').join('\n') + '\n');
}

await walk();
const map = JSON.parse(await readFile(path.join(root, mapPath), 'utf8'));
const entries = new Map(map.files.map((entry) => [entry.path.replaceAll('\\', '/'), entry]));
const missing = [...entries.keys()].filter((file) => !actual.has(file));
if (missing.length) {
  console.error('Refusing to silently remove missing inventory entries:');
  missing.forEach((file) => console.error(`MISSING: ${file}`));
  process.exit(1);
}

for (const file of actual) {
  if (!entries.has(file)) {
    entries.set(file, {
      path: file,
      area: areaOf(file),
      status: 'NEEDS_REVIEW',
      functional_title: path.basename(file),
      current_responsibility: 'Newly discovered file; responsibility and implementation status have not yet been reviewed.',
      next_action: 'Inspect, classify and document before implementation or deletion.',
      explicit_references: [],
      notes: 'Automatically added by refresh-project-inventory.mjs; manual classification required.'
    });
  }
}

map.files = [...entries.values()].sort((a, b) => a.path.localeCompare(b.path));
map.summary.file_count = actual.size;
map.summary.total_files = actual.size;
map.summary.status_counts = Object.fromEntries([...map.files.reduce((counts, entry) => counts.set(entry.status, (counts.get(entry.status) || 0) + 1), new Map())].sort(([a], [b]) => a.localeCompare(b)));
map.summary.note = 'Generated by scripts/refresh-project-inventory.mjs. AI_PROJECT_MAP.json and FILE_INDEX.json self-hashes are null to avoid recursive hashes.';

async function refreshHashes() {
  for (const entry of map.files) {
    const file = entry.path;
    if (selfHashPaths.has(file)) entry.sha256 = null;
    else entry.sha256 = sha(await readFile(path.join(root, file)));
    entry.bytes = (await stat(path.join(root, file))).size;
  }
}

await refreshHashes();
await writeFile(path.join(root, mapPath), JSON.stringify(map, null, 2) + '\n');

const fields = ['path', 'area', 'status', 'functional_title', 'user_role', 'user_visible_behavior', 'current_responsibility', 'planned_responsibility', 'next_action', 'completion_definition'];
const csv = '\uFEFF' + [fields.join(','), ...map.files.map((entry) => fields.map((field) => csvCell(entry[field])).join(','))].join('\r\n') + '\r\n';
await writeFile(path.join(root, 'docs/AI_PROJECT_MAP.csv'), csv, 'utf8');
const md = [
  '# HANSALEHLAK — Current Project File Map', '',
  'Generated from `AI_PROJECT_MAP.json`. AI agents should use `docs/AI_CONTEXT/FILE_INDEX.json` for quick lookup.', '',
  '| Path | Status | Responsibility | Next action |', '|---|---|---|---|',
  ...map.files.map((entry) => `| ${String(entry.path).replaceAll('|', '\\|')} | ${String(entry.status || '').replaceAll('|', '\\|')} | ${String(entry.current_responsibility || '').replaceAll('|', '\\|').replaceAll('\n', ' ')} | ${String(entry.next_action || '').replaceAll('|', '\\|').replaceAll('\n', ' ')} |`)
].join('\n') + '\n';
await writeFile(path.join(root, 'docs/AI_PROJECT_MAP.md'), md);
await writeFile(path.join(root, 'docs/PROJECT_TREE.md'), await makeTree());

// Generated exports are now final; refresh their hashes in the canonical map.
await refreshHashes();
await writeFile(path.join(root, mapPath), JSON.stringify(map, null, 2) + '\n');
const index = {
  generated_from: mapPath,
  file_count: map.files.length,
  files: map.files.map((entry) => ({ path: entry.path, area: entry.area, status: entry.status, bytes: entry.bytes, sha256: entry.sha256 }))
};
await writeFile(path.join(root, indexPath), JSON.stringify(index, null, 2) + '\n');
console.log(`Refreshed ${map.files.length} inventory entries. New files are marked NEEDS_REVIEW until classified.`);
