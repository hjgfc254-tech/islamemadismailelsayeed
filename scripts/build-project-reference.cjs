function settingsKeys() {
  const src = read('services/local-market-store.js') + read('services/admin-api.js') + read('functions/src/admin-extra.js');
  const keys = new Set();
  for (const m of src.matchAll(/settings\.([a-zA-Z]+)/g)) keys.add(m[1]);
  for (const m of src.matchAll(/setSetting\('([a-zA-Z]+)'/g)) keys.add(m[1]);
  return [...keys].sort();
}
function fileInventory() {
  let idx; try { idx = JSON.parse(read('docs/AI_CONTEXT/FILE_INDEX.json')); } catch { return '_FILE_INDEX.json missing_'; }
  const by = {};
  for (const f of idx.files || []) (by[f.area || 'other'] = by[f.area || 'other'] || []).push(f);
  return Object.keys(by).sort().map(a => `### ${a} (${by[a].length})\n\n| File | Status | Bytes |\n|---|---|---|\n` +
    by[a].map(f => `| \`${f.path}\` | ${f.status || ''} | ${f.bytes || ''} |`).join('\n')).join('\n\n');
}
function scripts() {
  try { const p = JSON.parse(read('package.json')); return Object.entries(p.scripts || {}).map(([k, v]) => `| \`npm run ${k}\` | \`${v}\` |`).join('\n'); } catch { return ''; }
}
