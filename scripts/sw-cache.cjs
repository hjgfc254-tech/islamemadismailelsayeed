#!/usr/bin/env node
/**
 * Service-worker cache guard.
 * The service worker serves same-origin files cache-first, so a returning visitor keeps the old files until the
 * CACHE name in service-worker.js changes. This guard fingerprints every file the site serves and records it next
 * to the cache name in service-worker.lock.json:
 *   node scripts/sw-cache.cjs --check   fails when served files changed but the cache name did not (used by npm test)
 *   node scripts/sw-cache.cjs --bump    increments the cache name's trailing number and records the new fingerprint
 * The fingerprint ignores line endings (CRLF / LF), like scripts/inventory-files.mjs.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.resolve(__dirname, '..');
const SW = path.join(ROOT, 'service-worker.js');
const LOCK = path.join(ROOT, 'service-worker.lock.json');
const SERVED_DIRS = ['apps', 'shared', 'services', 'assets'];
const SERVED_ROOT_FILES = ['index.html', 'manifest.json'];
/* Everything that is not a known binary is text: git normalises it (.gitattributes: text=auto eol=lf), including
   extension-less files such as a vendor LICENSE, so CRLF on Windows and LF on CI must hash the same. */
const BINARY = /\.(png|jpe?g|gif|webp|ico|woff2?|pdf|mp4|mp3|wav|zip)$/i;
const CACHE_RE = /const CACHE = '([^']+)';/;

function walk(dir, out) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out); else out.push(p);
  }
  return out;
}

function servedFiles() {
  const files = [];
  for (const d of SERVED_DIRS) if (fs.existsSync(path.join(ROOT, d))) walk(path.join(ROOT, d), files);
  for (const f of SERVED_ROOT_FILES) if (fs.existsSync(path.join(ROOT, f))) files.push(path.join(ROOT, f));
  return files.map(f => path.relative(ROOT, f).split(path.sep).join('/')).sort();
}

function fingerprint() {
  const h = crypto.createHash('sha256');
  for (const rel of servedFiles()) {
    let buf = fs.readFileSync(path.join(ROOT, rel));
    if (!BINARY.test(rel)) buf = Buffer.from(buf.toString('utf8').replace(/\r\n/g, '\n'), 'utf8');
    h.update(rel + '\0' + crypto.createHash('sha256').update(buf).digest('hex') + '\n');
  }
  return h.digest('hex');
}

const cacheName = () => { const m = fs.readFileSync(SW, 'utf8').match(CACHE_RE); if (!m) throw new Error('CACHE name not found in service-worker.js'); return m[1]; };
const readLock = () => (fs.existsSync(LOCK) ? JSON.parse(fs.readFileSync(LOCK, 'utf8')) : null);
const writeLock = (cache, hash) => fs.writeFileSync(LOCK, JSON.stringify({ cache, fingerprint: hash, note: 'Generated by `npm run sw:bump`. Do not edit by hand.' }, null, 2) + '\n');

/** @returns {{ok:boolean, message:string}} */
function check() {
  const lock = readLock();
  const cache = cacheName();
  const hash = fingerprint();
  if (!lock) return { ok: false, message: 'service-worker.lock.json is missing. Run `npm run sw:bump`.' };
  if (lock.cache !== cache) return { ok: false, message: `CACHE is '${cache}' but the lock records '${lock.cache}'. Run \`npm run sw:bump\` instead of editing the name by hand.` };
  if (lock.fingerprint !== hash) return { ok: false, message: `Served files changed but the service-worker cache is still '${cache}', so returning visitors would keep the old files. Run \`npm run sw:bump\`.` };
  return { ok: true, message: `service-worker cache '${cache}' matches the served files.` };
}

function bump() {
  const src = fs.readFileSync(SW, 'utf8');
  const cur = cacheName();
  const lock = readLock();
  const hash = fingerprint();
  if (lock && lock.cache === cur && lock.fingerprint === hash) return { cache: cur, changed: false };
  if (!lock) { writeLock(cur, hash); return { cache: cur, changed: false, created: true }; }   // first run: adopt the current name
  const m = cur.match(/^(.*?)(\d+)$/);
  if (!m) throw new Error(`cannot bump '${cur}': it has no trailing number`);
  const next = m[1] + (Number(m[2]) + 1);
  fs.writeFileSync(SW, src.replace(CACHE_RE, `const CACHE = '${next}';`));
  writeLock(next, fingerprint());   // service-worker.js itself is not a served file, so the fingerprint is unchanged
  return { cache: next, changed: true, from: cur };
}

module.exports = { check, bump, fingerprint, servedFiles, cacheName, readLock };

if (require.main === module) {
  const arg = process.argv[2];
  if (arg === '--bump') {
    const r = bump();
    console.log(r.changed ? `service-worker cache: ${r.from} -> ${r.cache}` : `service-worker cache '${r.cache}' is already current.`);
  } else {
    const r = check();
    (r.ok ? console.log : console.error)(r.message);
    process.exitCode = r.ok ? 0 : 1;
  }
}
